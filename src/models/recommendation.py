"""Pydantic v2 schemas for upgrade recommendations and AI provider services."""
from __future__ import annotations

from enum import Enum
from typing import List, Optional
from pydantic import BaseModel, Field

from src.models.manifest import Ecosystem, ManifestAnalysisResponse


class RecommendationCategory(str, Enum):
    """Categorization for upgrade recommendation safety and urgency."""
    RECOMMENDED = "RECOMMENDED"
    CAUTION = "CAUTION"
    NO_UPGRADE_NEEDED = "NO_UPGRADE_NEEDED"
    PRESERVED_UNSUPPORTED = "PRESERVED_UNSUPPORTED"


class RecommendationPriority(str, Enum):
    """Priority level for taking action on an upgrade."""
    CRITICAL = "CRITICAL"
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"


class ValidationStatus(str, Enum):
    """Ground truth registry verification status of candidate version."""
    VALIDATED = "VALIDATED"
    REJECTED_HALLUCINATION = "REJECTED_HALLUCINATION"
    FALLBACK_DETERMINISTIC = "FALLBACK_DETERMINISTIC"
    SKIPPED = "SKIPPED"


class ModelMetadata(BaseModel):
    """Metadata describing a discovered or configured AI model."""
    name: str = Field(..., description="Model identifier / tag name (e.g., 'llama3.2:latest')")
    model: Optional[str] = Field(default=None, description="Underlying model family or path")
    size_bytes: int = Field(default=0, description="Model file size in bytes")
    modified_at: Optional[str] = Field(default=None, description="Last modification timestamp")
    digest: Optional[str] = Field(default=None, description="Model digest hash")
    family: Optional[str] = Field(default=None, description="Model family (e.g., 'llama')")
    parameter_size: Optional[str] = Field(default=None, description="Parameter scale (e.g., '3B')")
    display_label: Optional[str] = Field(default=None, description="Human-readable label for UI selection")


class PackageUpgradeRecommendation(BaseModel):
    """Structured upgrade recommendation for a single package."""
    package_name: str = Field(..., description="Normalized package name")
    ecosystem: Ecosystem = Field(..., description="Target ecosystem (python or npm)")
    current_version: Optional[str] = Field(default=None, description="Currently declared or pinned version")
    declared_specifier: str = Field(default="", description="Original constraint specifier from manifest")
    latest_registry_version: Optional[str] = Field(default=None, description="Latest known release from registry")
    candidate_version: Optional[str] = Field(default=None, description="Recommended target version to upgrade to")
    category: RecommendationCategory = Field(..., description="Safety and urgency categorization")
    priority: RecommendationPriority = Field(..., description="Action priority")
    explanation: str = Field(..., description="Human-readable rationale for recommendation")
    breaking_changes_summary: Optional[str] = Field(default=None, description="Notes on breaking changes or migration risks")
    confidence_score: float = Field(default=1.0, ge=0.0, le=1.0, description="Confidence score from 0.0 to 1.0")
    provider_used: str = Field(default="deterministic", description="Identifier of the provider engine used")
    model_used: Optional[str] = Field(default=None, description="Name of the model if AI provider was used")
    is_ai_generated: bool = Field(default=False, description="Whether this recommendation was generated by an LLM")
    validation_status: ValidationStatus = Field(
        default=ValidationStatus.FALLBACK_DETERMINISTIC,
        description="Registry ground-truth validation outcome"
    )
    raw_line: Optional[str] = Field(default=None, description="Original manifest declaration line")
    line_number: Optional[int] = Field(default=None, description="Line number in original manifest")


class RecommendationBatchRequest(BaseModel):
    """Request payload for generating upgrade recommendations from analyzed dependencies."""
    manifest_analysis: ManifestAnalysisResponse = Field(..., description="Complete analyzed manifest payload from M2")
    preferred_model: Optional[str] = Field(default=None, description="Optional preferred model tag for AI inference")
    force_deterministic: bool = Field(default=False, description="If true, bypass AI even if available and use deterministic engine")


class RecommendationBatchResponse(BaseModel):
    """Aggregated batch response containing upgrade recommendations for all dependencies."""
    manifest_type: str = Field(..., description="Source manifest type analyzed")
    ecosystem: Ecosystem = Field(..., description="Target ecosystem")
    recommendations: List[PackageUpgradeRecommendation] = Field(default_factory=list)
    provider_used: str = Field(..., description="Provider engine used ('ollama' or 'deterministic')")
    model_used: Optional[str] = Field(default=None, description="Model tag used if AI provider was active")
    is_offline_fallback: bool = Field(default=False, description="True if fallback was triggered due to offline/unreachable AI")
    total_upgrades_recommended: int = Field(default=0, description="Count of packages with upgrade recommended")
    total_caution: int = Field(default=0, description="Count of packages requiring caution / breaking change review")
    summary: str = Field(default="", description="High-level executive summary of recommendations")


class AIProviderStatusResponse(BaseModel):
    """Health and model discovery status for the AI service."""
    is_available: bool = Field(..., description="Whether the local AI provider daemon is active and responsive")
    provider_name: str = Field(..., description="Name of the AI provider (e.g. 'ollama')")
    endpoint: str = Field(..., description="Configured endpoint URL (sanitized)")
    discovered_models: List[ModelMetadata] = Field(default_factory=list, description="Locally installed models discovered dynamically")
    default_model: Optional[str] = Field(default=None, description="Default model selected for inference")
    message: str = Field(..., description="Diagnostic or status message")
