"""Registry ground-truth validator for AI upgrade recommendations."""
from __future__ import annotations

import logging
from typing import Dict, List, Optional

from src.models.manifest import AnalyzedDependency, DependencyStatus
from src.models.recommendation import (
    PackageUpgradeRecommendation,
    RecommendationCategory,
    ValidationStatus,
)

logger = logging.getLogger("dua.ai.validator")


class RegistryGroundTruthValidator:
    """Validates candidate upgrade versions suggested by AI against deterministic registry ground truth.
    
    Invariant: AI is strictly an advisory engine. External package registries (PyPI, npm)
    are the sole authority for package version existence. Non-existent, hallucinated,
    or incompatible versions are unconditionally rejected and reverted to deterministic candidates.
    """

    def validate_recommendation(
        self,
        recommendation: PackageUpgradeRecommendation,
        dependency: AnalyzedDependency,
    ) -> PackageUpgradeRecommendation:
        """Validate a single recommendation against its corresponding analyzed dependency ground truth."""
        # 1. Skipped cases (no upgrade needed, preserved, or deterministic fallback)
        if (
            recommendation.candidate_version is None
            or recommendation.category in (
                RecommendationCategory.NO_UPGRADE_NEEDED,
                RecommendationCategory.PRESERVED_UNSUPPORTED,
            )
            or dependency.status in (
                DependencyStatus.UP_TO_DATE,
                DependencyStatus.PRESERVED,
            )
        ):
            return recommendation.model_copy(update={
                "validation_status": ValidationStatus.SKIPPED
            })

        # If already generated by deterministic fallback engine, preserve FALLBACK_DETERMINISTIC status
        if not recommendation.is_ai_generated:
            return recommendation.model_copy(update={
                "validation_status": ValidationStatus.FALLBACK_DETERMINISTIC
            })

        # 2. Check candidate version against registry available versions and known latest releases
        cand = recommendation.candidate_version.strip()
        known_versions = set(dependency.available_versions)
        if dependency.latest_version:
            known_versions.add(dependency.latest_version)
        if dependency.latest_compatible_version:
            known_versions.add(dependency.latest_compatible_version)

        # Check if candidate exists in verified registry versions
        is_known = cand in known_versions

        if is_known:
            logger.debug(
                f"Candidate '{cand}' for '{dependency.name}' validated against registry ground truth."
            )
            return recommendation.model_copy(update={
                "validation_status": ValidationStatus.VALIDATED,
            })

        # 3. Hallucination detected! Candidate does not exist in registry ground truth
        safe_fallback = (
            dependency.latest_compatible_version
            or dependency.latest_version
            or dependency.current_version
        )
        logger.warning(
            f"AI suggested hallucinated version '{cand}' for '{dependency.name}'. "
            f"Version does not exist in {dependency.ecosystem.value} registry. "
            f"Reverting to verified candidate '{safe_fallback}'."
        )

        orig_explanation = recommendation.explanation
        rejection_notice = (
            f"[REJECTED HALLUCINATION] AI proposed version '{cand}', which does not exist in "
            f"the {dependency.ecosystem.value} registry. Reverted to verified candidate '{safe_fallback}'. "
        )

        return recommendation.model_copy(update={
            "candidate_version": safe_fallback,
            "validation_status": ValidationStatus.REJECTED_HALLUCINATION,
            "explanation": rejection_notice + orig_explanation,
            "is_ai_generated": False,
            "confidence_score": 0.5,
        })

    def validate_batch(
        self,
        recommendations: List[PackageUpgradeRecommendation],
        dependencies: List[AnalyzedDependency],
    ) -> List[PackageUpgradeRecommendation]:
        """Validate a list of recommendations against their analyzed dependencies."""
        dep_map: Dict[str, AnalyzedDependency] = {d.name.lower(): d for d in dependencies}
        validated: List[PackageUpgradeRecommendation] = []

        for rec in recommendations:
            dep = dep_map.get(rec.package_name.lower())
            if dep is None:
                # If dependency not found in map, mark unvalidated / skipped
                validated.append(rec)
            else:
                validated.append(self.validate_recommendation(rec, dep))

        return validated
