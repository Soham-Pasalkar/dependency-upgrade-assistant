"""Registry ground-truth and constraint compatibility validator for AI upgrade recommendations."""
from __future__ import annotations

import logging
from typing import Dict, List, Optional, Set

from packaging.specifiers import InvalidSpecifier, SpecifierSet
from packaging.version import InvalidVersion, Version as PyVersion

from src.analysis.semver_evaluator import SemVer, semver_satisfies
from src.models.manifest import AnalyzedDependency, DependencyStatus, Ecosystem
from src.models.recommendation import (
    PackageUpgradeRecommendation,
    RecommendationCategory,
    RecommendationPriority,
    ValidationStatus,
)

logger = logging.getLogger("dua.ai.validator")


class RegistryGroundTruthValidator:
    """Validates candidate upgrade versions suggested by AI against deterministic registry ground truth
    and ecosystem-specific constraint compatibility rules.
    
    Invariants:
    1. AI is strictly an advisory engine. External registries (PyPI, npm) are the sole authority
       for version existence and metadata truth.
    2. Candidate versions must exist in verified registry metadata. Hallucinations are rejected.
    3. Downgrades (candidate < current) are strictly rejected as incompatible.
    4. Stable releases must not be upgraded to prereleases unless current is already a prerelease.
    5. In-range vs out-of-range target upgrades are distinguished:
       - In-range upgrades satisfy declared manifest constraints.
       - Exact pin bumps or major jumps exceeding declared ranges require CAUTION and M4 constraint modification.
    6. Fail-closed fallback: When an AI candidate is rejected, revert to an explicitly verified M2 candidate
       if available. If no verified compatible candidate exists, return a safe no-recommendation/preserved result.
       Never substitute an unverified latest_version as a supposedly safe fallback.
    """

    def validate_recommendation(
        self,
        recommendation: PackageUpgradeRecommendation,
        dependency: AnalyzedDependency,
    ) -> PackageUpgradeRecommendation:
        """Validate a single recommendation against its corresponding analyzed dependency ground truth."""
        # 1. Skipped cases (already up to date, preserved, or generated by deterministic fallback)
        if dependency.status == DependencyStatus.UP_TO_DATE and (
            not recommendation.candidate_version or recommendation.candidate_version == dependency.current_version
        ):
            return recommendation.model_copy(update={
                "candidate_version": dependency.current_version,
                "category": RecommendationCategory.NO_UPGRADE_NEEDED,
                "priority": RecommendationPriority.LOW,
                "validation_status": ValidationStatus.SKIPPED,
                "is_ai_generated": False,
            })

        if dependency.status == DependencyStatus.PRESERVED:
            return recommendation.model_copy(update={
                "candidate_version": None,
                "category": RecommendationCategory.PRESERVED_UNSUPPORTED,
                "priority": RecommendationPriority.LOW,
                "validation_status": ValidationStatus.SKIPPED,
                "is_ai_generated": False,
            })

        if not recommendation.is_ai_generated:
            # Deterministic engine output is preserved as FALLBACK_DETERMINISTIC
            return recommendation.model_copy(update={
                "validation_status": ValidationStatus.FALLBACK_DETERMINISTIC
            })

        cand = recommendation.candidate_version.strip() if recommendation.candidate_version else None
        if not cand:
            return self._fail_closed_fallback(
                recommendation,
                dependency,
                rejection_reason="AI response omitted a candidate version",
                status=ValidationStatus.REJECTED_INCOMPATIBLE,
            )

        # 2. Registry existence check (ground truth from M2)
        known_versions: Set[str] = set(dependency.available_versions)
        if dependency.latest_version:
            known_versions.add(dependency.latest_version)
        if dependency.latest_compatible_version:
            known_versions.add(dependency.latest_compatible_version)

        if cand not in known_versions:
            logger.warning(
                f"AI suggested hallucinated version '{cand}' for '{dependency.name}'. "
                f"Version does not exist in {dependency.ecosystem.value} registry."
            )
            return self._fail_closed_fallback(
                recommendation,
                dependency,
                rejection_reason=f"Proposed version '{cand}' does not exist in {dependency.ecosystem.value} registry ground truth",
                status=ValidationStatus.REJECTED_HALLUCINATION,
                hallucinated_version=cand,
            )

        # 3. Parseability and Syntax Validation
        cand_py: Optional[PyVersion] = None
        curr_py: Optional[PyVersion] = None
        cand_sem: Optional[SemVer] = None
        curr_sem: Optional[SemVer] = None

        if dependency.ecosystem == Ecosystem.PYTHON:
            try:
                cand_py = PyVersion(cand)
            except InvalidVersion:
                return self._fail_closed_fallback(
                    recommendation,
                    dependency,
                    rejection_reason=f"Candidate '{cand}' is not a valid PEP 440 version",
                    status=ValidationStatus.REJECTED_INCOMPATIBLE,
                )
            if dependency.current_version:
                try:
                    curr_py = PyVersion(dependency.current_version)
                except InvalidVersion:
                    pass
        else:  # NPM
            cand_sem = SemVer.parse(cand)
            if cand_sem is None:
                return self._fail_closed_fallback(
                    recommendation,
                    dependency,
                    rejection_reason=f"Candidate '{cand}' is not a valid SemVer 2.0.0 version",
                    status=ValidationStatus.REJECTED_INCOMPATIBLE,
                )
            if dependency.current_version:
                curr_sem = SemVer.parse(dependency.current_version)

        # 4. Downgrade Prevention
        if dependency.ecosystem == Ecosystem.PYTHON and curr_py is not None and cand_py is not None:
            if cand_py < curr_py:
                return self._fail_closed_fallback(
                    recommendation,
                    dependency,
                    rejection_reason=f"Candidate '{cand}' is lower than current version '{dependency.current_version}' (downgrade prevention)",
                    status=ValidationStatus.REJECTED_INCOMPATIBLE,
                )
            if cand_py == curr_py:
                return recommendation.model_copy(update={
                    "candidate_version": dependency.current_version,
                    "category": RecommendationCategory.NO_UPGRADE_NEEDED,
                    "priority": RecommendationPriority.LOW,
                    "explanation": f"Package '{dependency.name}' is already at version '{cand}'.",
                    "validation_status": ValidationStatus.SKIPPED,
                    "is_ai_generated": False,
                })
        elif dependency.ecosystem == Ecosystem.NPM and curr_sem is not None and cand_sem is not None:
            if cand_sem < curr_sem:
                return self._fail_closed_fallback(
                    recommendation,
                    dependency,
                    rejection_reason=f"Candidate '{cand}' is lower than current version '{dependency.current_version}' (downgrade prevention)",
                    status=ValidationStatus.REJECTED_INCOMPATIBLE,
                )
            if cand_sem == curr_sem:
                return recommendation.model_copy(update={
                    "candidate_version": dependency.current_version,
                    "category": RecommendationCategory.NO_UPGRADE_NEEDED,
                    "priority": RecommendationPriority.LOW,
                    "explanation": f"Package '{dependency.name}' is already at version '{cand}'.",
                    "validation_status": ValidationStatus.SKIPPED,
                    "is_ai_generated": False,
                })

        # 5. Prerelease Policy Enforcement
        cand_is_prerelease = False
        curr_is_prerelease = False

        if dependency.ecosystem == Ecosystem.PYTHON:
            cand_is_prerelease = cand_py.is_prerelease if cand_py else False
            curr_is_prerelease = curr_py.is_prerelease if curr_py else False
        else:
            cand_is_prerelease = cand_sem.is_prerelease() if cand_sem else False
            curr_is_prerelease = curr_sem.is_prerelease() if curr_sem else False

        if cand_is_prerelease and not curr_is_prerelease:
            return self._fail_closed_fallback(
                recommendation,
                dependency,
                rejection_reason=f"Candidate '{cand}' is an unstable prerelease, but current version '{dependency.current_version}' is stable",
                status=ValidationStatus.REJECTED_INCOMPATIBLE,
            )

        # 6. Constraint Compatibility and Upgrade Target Classification
        specifier_str = dependency.declared_specifier.strip() if dependency.declared_specifier else ""
        is_range = any(op in specifier_str for op in ("^", "~", "<", ">", "!="))
        is_exact_pin = False

        if specifier_str.startswith("==") or specifier_str.startswith("===") or (
            dependency.ecosystem == Ecosystem.NPM and SemVer.parse(specifier_str) is not None
        ):
            is_exact_pin = True

        is_constraint_compatible = False
        if not specifier_str or specifier_str == "*":
            is_constraint_compatible = True
        elif not is_range and is_exact_pin:
            is_constraint_compatible = False
        else:
            if dependency.ecosystem == Ecosystem.PYTHON and cand_py:
                try:
                    spec_set = SpecifierSet(specifier_str)
                    is_constraint_compatible = cand_py in spec_set
                except (InvalidSpecifier, InvalidVersion):
                    is_constraint_compatible = False
            elif dependency.ecosystem == Ecosystem.NPM and cand_sem:
                is_constraint_compatible = semver_satisfies(cand_sem, specifier_str)

        # Classify based on constraint compatibility and target
        updated_category = recommendation.category
        updated_priority = recommendation.priority
        updated_explanation = recommendation.explanation

        if is_constraint_compatible:
            # Candidate strictly satisfies declared manifest constraints
            logger.debug(f"Candidate '{cand}' satisfies declared constraint '{specifier_str}'.")
            if dependency.yanked_or_deprecated:
                updated_category = RecommendationCategory.CAUTION
                updated_priority = RecommendationPriority.CRITICAL
        elif is_exact_pin:
            # Candidate is a verified target to upgrade an exact pin (e.g. ==2.25.0 -> 2.32.3)
            # Modifying an exact pin requires caution and M4 manifest mutation
            updated_category = RecommendationCategory.CAUTION
            if dependency.yanked_or_deprecated:
                updated_priority = RecommendationPriority.CRITICAL
            elif updated_priority == RecommendationPriority.LOW:
                updated_priority = RecommendationPriority.MEDIUM
            pin_note = (
                f"Upgrade target '{cand}' bumps exact pin '{specifier_str}'. "
                f"Will require updating the manifest pin in M4."
            )
            if pin_note not in updated_explanation:
                updated_explanation = f"{pin_note} {updated_explanation}".strip()
        elif is_range and not is_constraint_compatible:
            return self._fail_closed_fallback(
                recommendation,
                dependency,
                rejection_reason=f"Candidate '{cand}' violates declared constraint '{specifier_str}'",
                status=ValidationStatus.REJECTED_INCOMPATIBLE,
            )
        else:
            return self._fail_closed_fallback(
                recommendation,
                dependency,
                rejection_reason=f"Candidate '{cand}' does not satisfy compatibility requirements for '{specifier_str}'",
                status=ValidationStatus.REJECTED_INCOMPATIBLE,
            )

        return recommendation.model_copy(update={
            "candidate_version": cand,
            "category": updated_category,
            "priority": updated_priority,
            "explanation": updated_explanation,
            "validation_status": ValidationStatus.VALIDATED,
            "is_ai_generated": True,
        })

    def _fail_closed_fallback(
        self,
        recommendation: PackageUpgradeRecommendation,
        dependency: AnalyzedDependency,
        rejection_reason: str,
        status: ValidationStatus,
        hallucinated_version: Optional[str] = None,
    ) -> PackageUpgradeRecommendation:
        """Apply fail-closed fallback when an AI candidate is rejected.
        
        If an explicitly verified compatible M2 candidate exists, fall back to it.
        Otherwise, return a safe no-upgrade/preserved result. Never substitute latest_version blindly.
        """
        # Check if an explicitly verified compatible candidate is available from M2
        safe_candidate: Optional[str] = None
        known_versions: Set[str] = set(dependency.available_versions)
        if dependency.latest_version:
            known_versions.add(dependency.latest_version)

        compat_source = dependency.latest_compatible_version or (
            dependency.latest_version if not dependency.declared_specifier else None
        )
        if compat_source:
            compat = compat_source.strip()
            if compat in known_versions and compat != dependency.current_version:
                # Verify that compatible version is strictly newer than current
                is_newer = False
                try:
                    if dependency.ecosystem == Ecosystem.PYTHON:
                        if dependency.current_version:
                            is_newer = PyVersion(compat) > PyVersion(dependency.current_version)
                        else:
                            is_newer = True
                    else:
                        compat_sem = SemVer.parse(compat)
                        curr_sem = SemVer.parse(dependency.current_version) if dependency.current_version else None
                        if compat_sem and (curr_sem is None or compat_sem > curr_sem):
                            is_newer = True
                except Exception:
                    is_newer = False

                if is_newer:
                    safe_candidate = compat

        status_tag = f"[{status.value.replace('_', ' ')}]"
        if safe_candidate:
            prefix = (
                f"{status_tag} {rejection_reason}. "
                f"Reverted to verified compatible candidate '{safe_candidate}'. "
            )
            return recommendation.model_copy(update={
                "candidate_version": safe_candidate,
                "validation_status": status,
                "explanation": (prefix + (recommendation.explanation or "")).strip(),
                "is_ai_generated": False,
                "confidence_score": 0.5,
            })

        # No verified compatible candidate available: fail-closed with safe no-upgrade result
        prefix = (
            f"{status_tag} {rejection_reason}. "
            f"No verified compatible upgrade candidate exists in registry metadata. Preserved without upgrade."
        )
        return recommendation.model_copy(update={
            "candidate_version": None,
            "category": RecommendationCategory.NO_UPGRADE_NEEDED,
            "priority": RecommendationPriority.LOW,
            "validation_status": status,
            "explanation": prefix,
            "breaking_changes_summary": None,
            "is_ai_generated": False,
            "confidence_score": 0.0,
        })

    def validate_batch(
        self,
        recommendations: List[PackageUpgradeRecommendation],
        dependencies: List[AnalyzedDependency],
    ) -> List[PackageUpgradeRecommendation]:
        """Validate a list of recommendations against their analyzed dependencies."""
        dep_map: Dict[str, AnalyzedDependency] = {d.name.lower(): d for d in dependencies}
        validated: List[PackageUpgradeRecommendation] = []

        for rec in recommendations:
            dep = dep_map.get(rec.package_name.lower())
            if dep is None:
                # Unknown package in recommendation: mark unverified / skipped
                validated.append(rec.model_copy(update={
                    "candidate_version": None,
                    "category": RecommendationCategory.PRESERVED_UNSUPPORTED,
                    "validation_status": ValidationStatus.REJECTED_INCOMPATIBLE,
                    "explanation": f"[REJECTED_INCOMPATIBLE] Package '{rec.package_name}' was not present in the analyzed manifest.",
                    "is_ai_generated": False,
                }))
            else:
                validated.append(self.validate_recommendation(rec, dep))

        return validated
